"""
Модуль 3.0 — Конфігурація логіки масштабування.

Усі пороги та параметри зібрані в одному місці навмисно: на захисті
комісія може запитати "чому саме таке значення X" — маючи все в одному
файлі з коментарями, легше пояснити кожен вибір, а не шукати магічні
числа розкидані по коду.
"""

from dataclasses import dataclass


@dataclass
class ScalingConfig:
    # --- Проактивний рівень (decision_engine.py) ---
    min_replicas: int = 2
    max_replicas: int = 20

    # Скільки навантаження (RPS) витримує ОДНА репліка на "нормальному"
    # (не пограничному) рівні — базова одиниця для перерахунку
    # прогноз → кількість реплік. Підбирається емпірично під ваш
    # тестовий сервіс (Модуль 4, Locust) або з документації реального
    # сервісу, якщо такий є.
    capacity_per_replica_rps: float = 50.0

    # Запас поверх точного розрахунку — компенсує похибку прогнозу
    # LSTM (MAE з Модуля 2) і час, потрібний поду на "розігрів"
    # (readiness probe, JIT-прогрів застосунку тощо)
    safety_factor: float = 1.15

    # Мінімальний час між послідовними актами масштабування (секунди).
    # Без цього прогноз, що коливається біля порогу, спричиняє
    # "тремтіння" (flapping) — модель то піднімає, то опускає репліки
    # щохвилини, що саме по собі шкодить стабільності системи.
    # 120с — типове значення, узгоджене з дефолтним stabilization
    # window реального Kubernetes HPA.
    cooldown_seconds: int = 120

    # --- Реактивний коректор (queuing_corrector.py) ---
    # Скільки запитів/сек обробляє одна репліка як M/M/c-сервер
    # (може відрізнятись від capacity_per_replica_rps вище: тут це
    # "сервісний темп" у термінах теорії черг, а не бізнес-поріг)
    service_rate_per_replica: float = 55.0

    # SLA: максимальний прийнятний час очікування запиту в черзі
    # (секунди), перш ніж реактивний коректор підніме тривогу і
    # додасть репліки понад те, що порахував проактивний прогноз
    max_wait_time_sec: float = 1.5

    # --- Kubernetes ---
    deployment_name: str = "autoscaling-demo-service"
    namespace: str = "default"